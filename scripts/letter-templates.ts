/**
 * Single-stroke letter templates in a unit cap-height box (y up, x in [0, width]).
 * Letters that normally need pen lifts are approximated by a continuous stroke
 * that a race track could plausibly trace (hairpins instead of retraces).
 */
export type Stroke = [number, number][];

const circleArc = (cx: number, cy: number, r: number, a0: number, a1: number, n = 24): Stroke =>
  Array.from({ length: n }, (_, i) => {
    const a = a0 + ((a1 - a0) * i) / (n - 1);
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
  });

